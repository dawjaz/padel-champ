/** Names that follow a pattern (gear: brand + grade + piece) instead of one entry each. Brand names stay as they are. */
const GRADE: Record<string, [string, string, string, string]> = {
  Basic: ['Básica', 'Básico', 'Básicas', 'Básicos'],
  Pro: ['Pro', 'Pro', 'Pro', 'Pro'],
  Technical: ['Técnica', 'Técnico', 'Técnicas', 'Técnicos'],
  Elite: ['Élite', 'Élite', 'Élite', 'Élite'],
};
const PIECE: Record<string, [string, number]> = {
  Shirt: ['Camiseta', 0],
  Shorts: ['Pantalón corto', 1],
  Shoes: ['Zapatillas', 2],
  Bag: ['Bolsa', 0],
};
export function patternEs(text: string): string | undefined {
  const m = /^(\S+) (Basic|Pro|Technical|Elite) (Shirt|Shorts|Shoes|Bag)$/i.exec(text);
  if (!m) return undefined;
  const cap = (t: string): string => t[0].toUpperCase() + t.slice(1).toLowerCase();
  const [piece, form] = PIECE[cap(m[3])];
  return `${piece} ${GRADE[cap(m[2])][form]} ${m[1]}`;
}
